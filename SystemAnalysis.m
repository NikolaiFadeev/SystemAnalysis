(*Given the MI,matrix M and RHS of some system,builds the system D[MI,x]\[Equal]M.MI+rg,where rg is a generic right-hand side (for the purpose of general solving using SolveDE).Also returns a set of rules rulesRgToRHS to convert back the generic RHS (rg) to the actual one (RHS)*)Clear[sysWithGenRHS];
sysWithGenRHS[MI_,M_,RHS_,Rg_,x_]:=Module[{rgArray,rulesRgToRHS,genSys},rgArray=Table[Rg[i][x],{i,1,Length[MI]}];
rulesRgToRHS=Thread[(rgArray)->(RHS)];
genSys=Thread[D[MI,x]==M . MI+rgArray];
{genSys,rulesRgToRHS}];


(*Given a set of rules of the form {MI_i\[Rule]{BI_1,...,BI_n}}_i, inverts them to get rules of the form {BI_i\[Rule]{MI_(j_1),...,MI_(j_i)}}_i, i.e. inverses the dependence rules from MI=MI(BI) to BI=BI(MI)*)
Clear[invertRules];
invertRules[ruleList_,setBI_]:=(#-> Cases[ruleList,HoldPattern[var_-> {___,#,___}]:> var])&/@setBI;


(*Applies the set of rules to the list of object taking into account the fact the variables that need to be replaced might appear as any order derivatives, i.e. it replaces them also using "differentiated" rules*)
Clear[applyDRules];
applyDRules[list_,rules_,x_]:=
Module[{dRules,ruList},
dRules=D[rules,x];
ruList=list/.rules;
While[Not[(ruList/.dRules)===ruList],
ruList=ruList/.dRules;
dRules=D[dRules,x]
];
ruList
];


(*Given the system decomposed using the ToMatrixForm function (matForm), uncouples it and returns in particular the normalized HODE for the first MI and the relations to get the other MIs from the first MI (after solving the HODE). Note: We use the Z\[UDoubleDot]rcher scheme to uncouple the system and since we stay in the DE world (no recurrences and therefore we select (for the moment) always one MI with all the IC and the others with zero ICs), we always take the first MI from the MI list in matForm*)
Clear[simpUncpl];
simpUncpl[matForm_,x_,varRoot_,W_,R_]:=
Module[{masterInt,baseInt,allVar,coeffMatrix,rhs,genSys,rulesRtoRHS,WW,stdUncpl,normHODE,uncpl2RHS,uncpl2,uncpl3RHS,uncpl3},
masterInt=matForm[["MasterIntegrals"]];
baseInt=matForm[["BaseIntegrals"]];
allVar=Sort[masterInt~Join~baseInt];
coeffMatrix=matForm[["Matrix"]];
rhs=matForm[["RHS"]];
{genSys,rulesRtoRHS}=sysWithGenRHS[masterInt,coeffMatrix,rhs,R,x];
WW=Table[W[i][x],{i,1,Length[masterInt]}];
stdUncpl=OreSys`UncoupleDifferentialSystem[genSys,masterInt,WW,x,R,Method->OreSys`Zuercher];
normHODE=recBoundingEqn[stdUncpl[[1]][[1]],0,W,R,x][[1]];(*The 0 might be changed to some user-specified order.*)
uncpl2RHS=applyDRules[#[[2]]&/@stdUncpl[[2]],eqToRule[stdUncpl[[2]]],x];
uncpl2=Thread[(#[[1]]&/@stdUncpl[[2]])->( uncpl2RHS)];
(*We now do the same for the third entry of the uncoupling, in order to get the actual dependence of the n master integrals
on W[1][x] and its derivatives. We also collect the factors of W[1][x], its derivativesvarRoot_ but also the Subscript[R, g] vector elements
and their derivatives for easier replacement later.*)
uncpl3RHS=applyDRules[#[[2]]&/@stdUncpl[[3]],uncpl2,x]//Collect[#,{W[1][x],D[W[1][x],{x,n_.}],R[m_.][x],D[R[p_.][x],{x,q_.}]},Together]&;
(*We are ready now to replace the generic Subscript[R, g] by the real inhomogeneous part.
We collect also the W[1][x] variable, its derivatives but also the BIs and their derivatives.*)
uncpl3RHS=applyDRules[uncpl3RHS,rulesRtoRHS,x]//Collect[#,{W[1][x],D[W[1][x],{x,n_.}]}~Join~baseInt~Join~D[baseInt,{x,m_.}],Together]&;
uncpl3=Thread[(#[[1]]&/@stdUncpl[[3]])->( uncpl3RHS)];
normHODE=applyDRules[normHODE,rulesRtoRHS,x];
normHODE=applyDRules[normHODE,Reverse[uncpl3[[1]]],x];
uncpl3=applyDRules[#,Reverse[uncpl3[[1]]],x]&/@uncpl3[[2;;]];
normHODE=normHODE[[1]]-normHODE[[2]]==0//Collect[#,If[Length[baseInt]>0,{W[1][x],D[W[1][x],{x,n_.}]}~Join~baseInt~Join~D[baseInt,{x,m_.}],{W[1][x],D[W[1][x],{x,n_.}]}],Together]&;
{{normHODE,uncpl3},OrderDE[normHODE,x,varRoot],masterInt,baseInt}
];


