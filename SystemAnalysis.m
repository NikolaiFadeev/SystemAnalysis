(*ToMatrixForm: Takes a system involving exclusively variables of the form var[__][x] and returns necessary information to write it in matrix form*)
ToMatrixForm[sys_,x_,varRoot_]:=
Module[{size,lenVarRoot,masterInt,mIL,baseInt,lhs,const,rhs,M,R},
(*We first check that the system is of the right form -- should be {a[1]\[Equal]b[1],...,a[n]\[Equal]b[n]}*)
Assert[Depth[sys]==3];
size=Length[sys];
lenVarRoot=StringLength[ToString[varRoot]];
(*Now we will extract the variables of our system (i.e. functions that are differentiated)*)
masterInt=DeleteDuplicates@Cases[sys,Derivative[n_][var_[y__]][x]/;Quiet[StringTake[ToString[var],lenVarRoot]]==ToString[varRoot]:>var[y][x],-1];
mIL=Length[masterInt];
(*These are the base integrals that must be given*)
baseInt=Complement[DeleteDuplicates@Cases[sys,var_[y__][x]/;Quiet[StringTake[ToString[var],lenVarRoot]]==ToString[varRoot],-1],masterInt];
(*Now we start to rewrite the system in a matrix form*)
(*First, we isolate the LHS and the RHS*)
lhs=Map[#[[1]]&,sys];
const=lhs/.Derivative[_][_][_]->1;
rhs=Map[#[[2]]&,sys];
rhs=Collect[rhs/const,var[__][x],Factor];
lhs=lhs/const;
(*We define now the coefficient matrix M*)
M=Table[Table[Coefficient[rhs[[i]],masterInt[[j]]],{j,1,mIL}],{i,1,Length[rhs]}];
(*And the inhomogeneous side*)
R=rhs/.Table[masterInt[[i]]->0,{i,1,mIL}];
R=Collect[R,{Derivative[n_.][var_[y__]][x]/;Quiet[StringTake[ToString[var],lenVarRoot]]==ToString[varRoot],var_[y__][x]/;Quiet[StringTake[ToString[var],lenVarRoot]]==ToString[varRoot]},Together];
(*We return the result in a form of an association (this is simply for legibility issues, it could be a list)*)
<|"Size"->size,"MasterIntegrals"->masterInt,"BaseIntegrals"->baseInt,"Matrix"->M,"RHS"->R|>
];


