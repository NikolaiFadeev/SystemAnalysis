(*recBoundingEqn: Takes the (uncoupled) equation eqn in one variable of the form Z[_][x], of order ordEqn 
(all the checks for consistency of the order of the equation are supposedly already done at this point), 
which contains occurence of elements of the vector {R[1][x],...,R[n][x]} of the general RHS of the initial system, 
and returns the maximal bounding of the recurence in n (equation (4.2) of article "A refined machinery to calculate 
large moments from coupled systems of linear differential equations") as well as the normalized equation in the form LHS\[Equal]0, 
where the LHS is of the form Subscript[\[Alpha], 0](x,\[Epsilon])Z[_](x)+...+Subscript[(D^\[Lambda]), x]Z[_](x)-\[Beta](x,\[Epsilon]), and all the Subscript[\[Alpha], i](x,\[Epsilon]) 
are normalized, i.e. their GCD=1*) 
Clear[recBoundingEqn];
recBoundingEqn[eqn_,ordEqn_,Z_,R_,x_]:=
Module[{eqnNorm,lcm,eqnWoutR,maxDeg,gcd},
(*Print[eqn," ",ordEqn," ",Z," ",R," ",x];*)
(*First, we transform eqn to LHS-RHS\[Equal]0 and take for computations LHS-RHS*)
eqnNorm=eqn[[1]]-eqn[[2]];
(*We compute the LCM of the denominators*)
lcm=PolynomialLCM@@Denominator[List@@eqnNorm];
(*Print["lcm = ",lcm];*)
(*We multiply by the lcm and simplify the equation*)
(*eqnNorm=Collect[eqnNorm*lcm,{Derivative[_][R[_]][x],R[_][x],Derivative[_][Z[_]][x],Z[_][x]},Together];*)
eqnNorm=Collect[eqnNorm*lcm,{Derivative[_][R[_]][x],R[_][x],Derivative[_][Z[_]][x],Z[_][x]},Together];
(*We extract the degrees (in x) of the polynomials \[Alpha](x,\[Epsilon]) that are the coefficients of the var[__][x] and (var^(n))[x] and compute their maximum*)
eqnWoutR=eqnNorm/.{Derivative[_][R[_]][x]->0,R[_][x]->0};
(*Print["eqnWoutR = ",eqnWoutR];*)
maxDeg=Max@Exponent[List@@eqnWoutR,x];
(*Print["maxDeg = ",maxDeg];*)
(*Finally, we search for the degree of the GCD of all the \[Alpha](x,\[Epsilon]) in order to be able to reduce the order of bounding of the difference equations*)
(*eqnWoutR=List@@eqnWoutR/.{D[_][Z[_]][x]\[Rule]1,Z[_][x]\[Rule]1};*) (*- this is the old version, in the case of trivial equation (e.g. Z[1][x]), gives the wrong answer due to List@@ Z*)
If[Length[eqnWoutR]==1,eqnWoutR=eqnWoutR/.{Derivative[_][Z[_]][x]->1,Z[_][x]->1},eqnWoutR=List@@eqnWoutR/.{Derivative[_][Z[_]][x]->1,Z[_][x]->1}];
(*Print["eqnWoutR = ",eqnWoutR];*)
gcd=PolynomialGCD@@eqnWoutR;
(*Print["gcd = ",gcd];*)
(*It suffices to collect and rearrange everything and return the result*)
(*Print["eqnNorm Gauss = ",eqnNorm];*)
eqnNorm=Collect[eqnNorm/gcd,{Derivative[_][R[_]][x],R[_][x],Derivative[_][Z[_]][x],Z[_][x]},Together];
(*Print["eqnNorm Gauss = ",eqnNorm];*)
{eqnNorm==0,ordEqn+maxDeg-Exponent[gcd,x]}
];


(*InitialValueSys: Given a system sys=M.MI+inhomogeneous_part of size size, in x, and Mexp the expansion of M in \[Epsilon] up to ord, 
the function uncouples the system and using the uncoupled higher order DE (HODE from now on) computes the number of IC required
for each MI.*)
(*Remark: The system "sys" should be the general one, including the RR in the RHS and not the particular RHS*)
Clear[InitialValueSys];
InitialValueSys[sys_,MI_,M_,size_,x_,ord_,Mexp_]:=
Module[{ZZ,unSys,higherOrderDE,standVar,ordVL,ordL,normHigherOrderDE,boundings,ordMax,ordTot,MIU,ZZtoMI,MIC},
(*Sanity checks*)
Assert[!ValueQ[Z]];
Assert[!ValueQ[R]];
(*We construct the dummy variable arrow that is needed for uncoupling*)
ZZ=Array[Z[#][x]&,size];
(*Print["(InitialValueSys) ZZ = ",ZZ];*)
(*We uncouple the system*)
unSys=AbsoluteTiming[OreSys`UncoupleDifferentialSystem[sys,MI,ZZ,x,R,Method->OreSys`Zuercher]];
Print["(InitialValueSys) unSys in ",unSys[[1]]," s"];
unSys=unSys[[2]];
higherOrderDE=unSys[[1]];
standVar=unSys[[3]];
(*Then, we simply find in which dummy variable Z[i] are (is) the uncoupling equation(s), and the order of the equation = number of required IC*)
ordVL=OrderDE[#,x,Z]&/@higherOrderDE;
ordL=#[[2]]&/@ordVL;
(*We check that no equation has more than one highest order derivative*)
Assert[Total[Length/@(#[[1]]&/@ordVL)]==Length[ordL]];
(*We compute the bounding for the associated difference equation*)
normHigherOrderDE=recBoundingEqn[#1,#2,Z,R,x]&@@@Thread[{higherOrderDE,ordL}];
(*Print["(IVS) normHigherOrderDE = ",normHigherOrderDE];*)
{normHigherOrderDE,boundings}=Thread[normHigherOrderDE];
(*Print["Normalized eqns = ",normHigherOrderDE];*)
(*The maximal order of the equation(s) will be useful when searching for the best uncoupling*)
ordMax=Max[ordL];
(*Here is the total order of the equation, corresponding to the total number of IC that we will need*)
ordTot=Total[ordL];
(*We add also all the Z[i] variables that don't appear in the uncoupling equation with a 0 -- meaning, 0 required I.C. (i.e. we add doublets of the form {Z[i][x],0})*)
ordVL=Flatten[Thread/@ordVL,1];
ordVL=ordVL~Join~Thread[{Complement[ZZ,#[[1]]&/@ordVL],0}];
(*Useful technicality: we go from a doublet {ZZ,N} representation to a rule representation {ZZ \[Rule] N}*)
ordVL=Thread[(#[[1]]&/@ordVL)->( #[[2]]&/@ordVL),List,2];
(*We extract the MI from the last part of the uncoupling...*)
MIU=#[[1]]&/@standVar;
(*...and their expression as a function of the dummy variables Y[i]*)
ZZtoMI=#[[2]]&/@standVar;
(*We extract all the occurence of the dummy variables from the RHS of the last part of the uncoupling result, i.e. we find explicitely on which dummy variables Y[i] depend explicitely the MI*)
ZZtoMI=DeleteDuplicates/@(Cases[List[#],Z[t__][x]:>Z[t][x],-1]&/@ZZtoMI);
(*Now, it suffices to replace the Y[i] by the number of I.C. they require (in variable ordVL), and take the total to get the number of I.C. required for each MI*)
ZZtoMI=Total[#[[1]]]&/@(ZZtoMI/.ordVL);
(*We compute the minimal order in \[Epsilon] for each MI in the matrix M and find the right order up to which we need to expand the IC*)
MIC=Thread[{MIU,ZZtoMI}];
<|"Uncoupling"->unSys,"NormalizedUncoupling"->normHigherOrderDE,"Boundings"->boundings,"TotalOrder"->ordTot,"MaximalOrder"->ordMax,"MasterIntegrals"->MIC|>
];


(*BaseIntegralOrder: Given the expanded RHS of the system, computes the required order of expansion of each of the BI appearing there*)
Clear[BaseIntegralOrder];
BaseIntegralOrder[BI_,RHSExp_,ord_,Ep_]:=Thread[{BI,ord-Min[MinOrder[#,Ep]&/@Coefficient[RHSExp,#]]&/@BI}];


(*MasterIntegralIC: Searches for the best uncoupling by cycling through the MI variables*)
Clear[MasterIntegralIC];
MasterIntegralIC[MI_,M_,size_,x_,ord_,Mexp_]:=
Module[{RR,sys,IVSInit,IVS,i},
(*Consistency checks*)
Assert[Length[M]==size];
Assert[size>=2];
(*Free variable check*)
Assert[!ValueQ[R]];
