Clear[convertHODE];
convertHODE[eqn_,MI_,BI_List,x_]:=convertHODE[eqn,MI,BI,x]=
(*Test to see whether we have a HODE (Equal) or a LF (Rule)*)
If[eqn[[1]]===MI,
eqn[[1]]==eqn[[2]]
,
With[{eqnOnlyLhs=(eqn[[1]]-eqn[[2]]==0)},(eqnOnlyLhs[[1]]/.(Thread[BI->0]~Join~Thread[D[BI,{x,n_.}]->0]))==(-eqnOnlyLhs[[1]]/.{MI->0,D[MI,{x,n_.}]->0})]
