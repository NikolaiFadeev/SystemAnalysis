(*OrderDE: Gives the order of the DE eqn in var[__][x] variables. Returns a list of the form {{var[Subscript[A, 1]][x],...,var[Subscript[A, n]][x]}, Ord} where var[Subscript[A, i]][x] are all the variables that appear with the (maximal) order Ord of differentiation (i.e. they appear as D[Ord][var[Subscript[A, i]]][x])*)
Clear[OrderDE];
OrderDE[eqn_,x_,varRoot_]:=OrderDE[eqn,x,varRoot]=
Module[{lenVarRoot,funList,maxOrder},
lenVarRoot=StringLength[ToString[varRoot]];
(*We search for all the derivatives of the variables var[__][x] (including of order zero, i.e. non-differentiated)*)
funList=Cases[eqn,Derivative[n_.][var_[y__]][x]/;Quiet[StringTake[ToString[var],lenVarRoot]]==ToString[varRoot]:>{var[y][x], n},-1]~Join~Cases[eqn,var_[y__][x]/;Quiet[StringTake[ToString[var],lenVarRoot]]==ToString[varRoot]:> {var[y][x],0},-1];(*We find the maximal order of differentiation maxOrder*)
maxOrder=Max[#[[2]]&/@funList];
(*We return all the variables var[__][x] that appear as D[maxOrder][var[__]][x] in the expression as well as maxOrder*)
Join[List@DeleteDuplicates@Cases[funList,{a_,maxOrder}:> a],{maxOrder}]
];


