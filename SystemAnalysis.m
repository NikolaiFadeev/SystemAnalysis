Clear[normMat];
normMat[M_]:=Sqrt[Tr[Transpose[M] . M]];


Clear[sumMat];
sumMat[M_]:=Sum[M[[i]][[j]],{i,1,Length@M},{j,1,Length@Transpose@M}];


(*maxN: Produces the matrix with maximal sum of coefficients and minimal norm*)
Clear[maxN];
maxN[listMat_]:=
Module[{i,tableN,maxSum,maxNormMat},
tableN=Table[{i,sumMat[i],-normMat[i]},{i,listMat}];
maxSum=Cases[tableN,{mat_,Max[#[[2]]&/@tableN],norm_}];
maxNormMat=Cases[maxSum,{mat_,sum_,Max[#[[3]]&/@maxSum]}:> mat];
Position[listMat,#]&/@maxNormMat//Flatten//DeleteDuplicates
];


(*minHODENum : Function that will allow to sort the possible answers by the number of HODE they have, to take in case there are still several solutions at the end one that has the fewer HODE possible*)
Clear[minHODENum];
minHODENum[solConfig_]:=
Module[{eqnSet},
eqnSet=#[[1]][[2]]&/@solConfig;
Total[If[Head[#]===Equal,1,0]&/@eqnSet]
];


(*selectSol: Function that computes the best solution out of all the possible "good" uncouplings that uncplTreeRec has found*)
