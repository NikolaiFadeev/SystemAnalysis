(*SystemAnalysis: Given a system sys in varRoot__[__][x], returns the best general uncoupling (so without expansions in \[Epsilon]) and information about the MI and BI*)
SystemAnalysisOld[sys_,x_,varRoot_,ord_,d_,Ep_]:=
Module[{return,matForm,MI,tempBI,BI,M,R,size,Mseries,Rseries},
(*We first get all the useful matrix building blocks for the system and their expansion in \[Epsilon]*)
matForm=AbsoluteTiming[ToMatrixForm[sys,x,varRoot]];
Print["(SystemAnalysis) to matForm in ",matForm[[1]]," s"];
matForm=matForm[[2]];
MI=matForm["MasterIntegrals"];
BI=matForm["BaseIntegrals"];
M=matForm["Matrix"];
R=matForm["RHS"];
size=matForm["Size"];
{Mseries,Rseries}=ToEp[M,R,ord,d,Ep];
(*We finally apply the MasterIntegralIC and BaseIntegralOrder algorithms and return the result*)
tempBI=AbsoluteTiming[BaseIntegralOrder[BI,Rseries,ord,Ep]];
(*Print["(SystemAnalysis) BaseIntegralOrder in ",tempBI[[1]]," s"];*)
tempBI=tempBI[[2]];
return=<|"BaseIntegrals"->BaseIntegralOrder[BI,Rseries,ord,Ep]|>;
PrependTo[return,MasterIntegralIC[MI,M,size,x,ord,Mseries]];
AppendTo[return,<|"RHS"->R|>];
return
];


