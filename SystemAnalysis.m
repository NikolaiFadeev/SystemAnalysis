]
,
{dblt,doubList}];
If[choice,
classList=DeleteDuplicates@DeleteCases[classList,{{{}},{MI_}}];
,
classList=DeleteDuplicates@classList
];
classList=Sort[classList,Length[#1[[2]]]<=Length[#2[[2]]]&]
];


