rhs=Cases[#,MI_/;MemberQ[lhs,MI]===True,-1]&/@(#[[2]]&/@sys);
{lhs,rhs,Thread[lhs->rhs]}
];


Clear[rulesFixedPoint];
rulesFixedPoint[obj_,rules_]:=
Module[{r1,r2,i=1},
While[True,
r1=Nest[DeleteDuplicates@Flatten@((#/.rules)~Join~{#})&,obj,i];
r2=Nest[DeleteDuplicates@Flatten@((#/.rules)~Join~{#})&,obj,i+1];
i=i+1;
If[Sort[r1]==Sort[r2],Break[]]];
r1
];


clusterVar[sys_,x_,varRoot_,choice_]:=
Module[{varList,rhsList,rulesList,depList,doubList,rulesBI,r1,r2,i=1,idCases,classList={}},
{varList,rhsList,rulesList}=sysRules[sys,x,varRoot];
rulesBI=Cases[rulesList,(var_->y__)/;Length[y]==0];
