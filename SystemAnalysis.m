(*Extracts the maximal factorizable power of \[Epsilon] from a ration function \[Alpha](x,\[Epsilon])*MI[x].
More precisely, given an element of the form (1) (a(x,\[Epsilon]))/(b(x,\[Epsilon]))*MI[x]=\[Epsilon]^r*(a'(x,\[Epsilon]))/(b'(x,\[Epsilon]))*MI[x],
where there exists no r'\[Element]Integers such that \[Epsilon]^r'|a'(x,\[Epsilon]) or \[Epsilon]^r'|b'(x,\[Epsilon]) (\[Epsilon]^r) maximal factor,
the function epPowerExpressions returns the value of r.
Note: Should be applied only on a monomial term of the form (1), and works always
as the pathological case when (1)=\[Epsilon]^p does never occur (worst case (1)=\[Epsilon]^p*MI[x] and this is fine)*)
Clear[epPowerExpressions];
SetAttributes[epPowerExpressions,Listable];
epPowerExpressions[expr_Power,d_,Ep_]:=Exponent[expr,Ep];
epPowerExpressions[expr_,d_,Ep_]:=Total@Cases[List@@(Factor[expr/.d->Ep+4]),Ep^n_.:> n];


(*Given a set of rules of the form {MI_i\[Rule]{BI_1,...,BI_n}}_i, inverts them to get rules of the form {BI_i\[Rule]{MI_(j_1),...,MI_(j_i)}}_i, i.e. inverses the dependence rules from MI=MI(BI) to BI=BI(MI)*)
