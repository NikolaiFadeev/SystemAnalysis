(*In a first step, we find which HODE is the best. We need for that a bestEqn function that, given the list of \[Epsilon] orders for the MIs HODEs or LFs, will return the best HODE(s)/LF(s) index (several if they are equal)*)
Clear[bestEqn];
Options[bestEqn]={"Scheme"->"Default"};
bestEqn[listEqn_,n_,x_,MI_,BI_,Ep_,INT_,OptionsPattern[]]:=
Module[{listEqnAndEp,corrListEqn,listEpOrd,trList,nVar,iMax,pos,return,i,j,nVarRules},
listEqnAndEp=epExtr/@listEqn;
listEpOrd=#[[2]]&/@listEqnAndEp;
(*Sanity check: all the elements of the listEpOrd must be of the same size (i.e. vectors of length = #BIs)*)
Assert[Equal@@Length/@listEpOrd];
(*We create the variables n[i] used for the computation of the maximum*)
nVar=Table[0,{Length@listEpOrd}];
(*We transpose the matrix in order to get row of \[Epsilon] coefficients for the same BIs*)
trList=Transpose@listEpOrd;
(*For each BIs, we find the maximal value of the \[Epsilon] power (i.e. the best since it "lowers" the order up to which we need
to expand the function), and then increase the corresponding nVar*)
For[i=1,i<=Length@trList,i++,
iMax=Max[trList[[i]]];
For[j=1,j<=Length@trList[[i]],j++,
If[trList[[i]][[j]]==iMax,nVar[[j]]++]
];
];
nVarRules=Thread[(#[[2]]&/@listEqnAndEp)->(-(List/@nVar))];
corrListEqn=listEqnAndEp/.nVarRules/.{{var_[x],expr_/;(Head[expr]===Equal||Head[expr]===Rule)},{m_Integer}}:>{{var[x],expr},Join[{m},extractRecOrder[expr,var[x],x,MI,BI,Ep,INT]]};
Which[OptionValue["Scheme"]==="Default",corrListEqn=Sort[corrListEqn,Total[#1[[2]]]<Total[#2[[2]]]&]
,
OptionValue["Scheme"]==="EpsOrder",corrListEqn=Sort[corrListEqn,{1,0,0} . (#1[[2]])<{1,0,0} . (#2[[2]])&]
,
OptionValue["Scheme"]==="DiffEqn",corrListEqn=Sort[corrListEqn,{0,1,0} . (#1[[2]])<{0,1,0} . (#2[[2]])&]
,
OptionValue["Scheme"]==="RecEqn",corrListEqn=Sort[corrListEqn,{0,0,1} . (#1[[2]])<{0,0,1} . (#2[[2]])&]
,
True,corrListEqn=Sort[corrListEqn,OptionValue["Scheme"][#1[[2]]]<OptionValue["Scheme"][#2[[2]]]&]
];
(*We find the HODE(s)/LF(s) corresponding to the maximal nVar, and return the corresponding equations*)
return=Cases[corrListEqn,{eqnSet_List,corrListEqn[[1,2]]}:>eqnSet];
return
