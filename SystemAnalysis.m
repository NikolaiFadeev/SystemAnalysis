gcd=If[Head[gcd]===Times,Apply[List,gcd],{gcd}];
gcd=Select[gcd,FreeQ[#,INT[__]]&];
gcd=Apply[Times,gcd];
deH=deH/gcd//Factor;
deH=Apply[Plus,deH]==0;
deH=DEToRE[deH,INT,x,N,False];
ord=N-Cases[{deH},INT[__][A_]->A,Infinity];
ordRec=Max[ord]-Min[{ord,0}];
{ordDiffEqn,ordRec}
